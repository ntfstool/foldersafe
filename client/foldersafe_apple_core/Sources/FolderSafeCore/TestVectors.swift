import Foundation
import CryptoKit

/// 规范 §10 的公开测试向量（docs/spec/test-vectors/v1.json）。
/// 所有输入（密钥、盐、nonce）都明文写在文件里，其他语言的实现不需要我们的随机数生成器就能逐字节复现。
public enum TestVectors {
    public enum Failure: Error, CustomStringConvertible {
        case mismatch(String)
        public var description: String { if case .mismatch(let s) = self { return "test vector mismatch: \(s)" }; return "" }
    }

    static let encKey = Encoding.unhex("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f")!
    static let macKey = Encoding.unhex("202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f")!

    static func pattern(_ n: Int) -> Data { Data((0..<n).map { UInt8($0 % 251) }) }

    public static func generate() throws -> Data {
        let key = Masterkey(encKey: encKey, macKey: macKey)
        let rnd = DeterministicRandom(seed: "FolderSafe test vectors v1")
        let names = NameCipher(key)
        var root: [String: Any] = [
            "description": "FolderSafe vault format v1 test vectors (docs/spec/vault-format-v1.md). Binary values are lower-case hex unless the field name says otherwise. Generated by client/foldersafe_apple_core (fsvault vectors).",
            "version": 1,
            "keys": ["encKey": Encoding.hex(encKey), "macKey": Encoding.hex(macKey),
                     "rawKey": Encoding.hex(key.raw), "sivKey_K1cmac_K2ctr": Encoding.hex(key.sivKey)],
        ]

        // AES-SIV（512 位密钥，与文件名加密同一用法）
        root["aesSiv"] = [("", ""), ("a", ""), ("hello.txt", "f5c8a3b6-3f0a-4c7e-9a1d-2b7c1e9d0a11"),
                          (String(repeating: "x", count: 40), "")].map { (p, ad) -> [String: Any] in
            let c = AESSIV.encrypt(key: key.sivKey, plaintext: Data(p.utf8), associatedData: [Data(ad.utf8)])
            return ["key": Encoding.hex(key.sivKey), "associatedData": [Encoding.hex(Data(ad.utf8))],
                    "plaintext": Encoding.hex(Data(p.utf8)), "ciphertext": Encoding.hex(c)]
        }

        // scrypt：规范默认参数
        let sSalt = rnd.bytes(32)
        root["scrypt"] = ["password": "password", "salt": Encoding.hex(sSalt), "N": 32768, "r": 8, "p": 1, "dkLen": 32,
                          "output": Encoding.hex(try Scrypt.derive(password: Data("password".utf8), salt: sSalt, n: 32768, r: 8, p: 1, length: 32))]

        // masterkey.cryptomator
        let pw = "Pässwörd 密码 123"     // 含非 ASCII，检验 UTF-8 / NFC
        let mkRandom = FixedRandom([rnd.bytes(32)])
        let mk = try MasterkeyFile.make(key, password: pw, random: mkRandom)
        root["masterkeyFile"] = ["password": pw, "passwordUtf8NFC": Encoding.hex(Data(pw.precomposedStringWithCanonicalMapping.utf8)),
                                 "scryptSalt": Encoding.hex(mk.scryptSalt), "N": mk.scryptCostParam, "r": mk.scryptBlockSize,
                                 "kek": Encoding.hex(try MasterkeyFile.kek(password: pw, salt: mk.scryptSalt, n: mk.scryptCostParam, r: mk.scryptBlockSize).withUnsafeBytes { Data($0) }),
                                 "file": String(decoding: mk.serialized(), as: UTF8.self)]

        // vault.cryptomator
        let vaultId = Vault.uuid(rnd)
        root["vaultConfig"] = ["vaultId": vaultId, "token": VaultConfig(vaultId: vaultId).token(signedWith: key)]

        // 目录 ID → 路径
        let subId = Vault.uuid(rnd)
        root["dirPaths"] = ["", subId].map { ["dirId": $0, "path": names.dirPath($0)] }

        // 文件名（含 NFD 输入、长名缩短）
        let longName = String(repeating: "长文件名", count: 30) + ".txt"
        root["names"] = [("hello.txt", ""), ("文档", ""), ("e\u{301}.txt", subId), (longName, subId)].map { (n, parent) -> [String: Any] in
            let enc = names.encrypt(n, parentDirId: parent)
            var v: [String: Any] = ["name": n, "nameUtf8NFC": Encoding.hex(Data(n.precomposedStringWithCanonicalMapping.utf8)),
                                    "parentDirId": parent, "encName": enc]
            if enc.count > 220 { v["shortened"] = NameCipher.shortened(enc) }
            return v
        }

        // 文件内容：明文按 pattern(i % 251) 生成；小文件给全文，大文件给 SHA-256
        root["fileContent"] = try [0, 5, 32768, 32769].map { size -> [String: Any] in
            let h = FileCipher.newHeader(rnd)
            let chunks = (size + FileCipher.chunkPlainSize - 1) / FileCipher.chunkPlainSize
            let nonces = (0..<chunks).map { _ in rnd.bytes(12) }
            let plain = pattern(size)
            var c = try FileCipher.encryptHeader(h, encKey: encKey)
            for i in 0..<chunks {
                let part = plain[(i * FileCipher.chunkPlainSize)..<min(size, (i + 1) * FileCipher.chunkPlainSize)]
                c += try FileCipher.encryptChunk(part, index: UInt64(i), header: h, nonce: nonces[i])
            }
            var v: [String: Any] = ["plaintextSize": size, "plaintext": "byte i = i mod 251",
                                    "headerNonce": Encoding.hex(h.nonce), "contentKey": Encoding.hex(h.contentKey),
                                    "chunkNonces": nonces.map { Encoding.hex($0) },
                                    "ciphertextSize": c.count, "ciphertextSha256": Encoding.hex(SHA256.hash(data: c))]
            if c.count <= 256 { v["ciphertext"] = Encoding.hex(c) }
            return v
        }

        // 找回短语 + recovery.json
        let phrase = RecoveryPhrase(entropy: rnd.bytes(16))
        let rec = try RecoveryFile.make(key, phrase: phrase, vaultId: vaultId, random: FixedRandom([rnd.bytes(32), rnd.bytes(12)]))
        root["recovery"] = ["entropy": Encoding.hex(phrase.entropy), "phrase": phrase.phrase, "vaultId": vaultId,
                            "salt": Encoding.hex(rec.salt), "nonce": Encoding.hex(rec.nonce),
                            "recoveryKey": Encoding.hex(RecoveryFile.key(phrase, salt: rec.salt).withUnsafeBytes { Data($0) }),
                            "file": String(decoding: rec.serialized(), as: UTF8.self)]

        return try JSONSerialization.data(withJSONObject: root, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([0x0a])
    }

    /// 用本实现逐项复核一份向量文件（加密方向逐字节比对，解密方向必须还原）。
    public static func verify(_ data: Data) throws {
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else { throw Failure.mismatch("not JSON") }
        func hex(_ any: Any?) throws -> Data {
            guard let s = any as? String, let d = Encoding.unhex(s) else { throw Failure.mismatch("hex field") }
            return d
        }
        func check(_ ok: Bool, _ what: String) throws { if !ok { throw Failure.mismatch(what) } }

        let keys = root["keys"] as? [String: Any] ?? [:]
        let key = Masterkey(encKey: try hex(keys["encKey"]), macKey: try hex(keys["macKey"]))
        try check(Encoding.hex(key.sivKey) == keys["sivKey_K1cmac_K2ctr"] as? String, "sivKey")
        let names = NameCipher(key)

        for v in root["aesSiv"] as? [[String: Any]] ?? [] {
            let k = try hex(v["key"]), p = try hex(v["plaintext"]), c = try hex(v["ciphertext"])
            let ad = try (v["associatedData"] as? [String] ?? []).map { try hex($0) }
            try check(AESSIV.encrypt(key: k, plaintext: p, associatedData: ad) == c, "aesSiv encrypt")
            try check((try? AESSIV.decrypt(key: k, ciphertext: c, associatedData: ad)) == p, "aesSiv decrypt")
        }

        if let s = root["scrypt"] as? [String: Any] {
            let out = try Scrypt.derive(password: Data((s["password"] as? String ?? "").utf8), salt: try hex(s["salt"]),
                                        n: s["N"] as? Int ?? 0, r: s["r"] as? Int ?? 0, p: s["p"] as? Int ?? 0, length: s["dkLen"] as? Int ?? 0)
            try check(out == (try hex(s["output"])), "scrypt")
        }

        if let m = root["masterkeyFile"] as? [String: Any], let file = m["file"] as? String, let pw = m["password"] as? String {
            let parsed = try MasterkeyFile(data: Data(file.utf8))
            try check(try parsed.unlock(password: pw) == key, "masterkeyFile unlock")
            let remade = try MasterkeyFile.make(key, password: pw, random: FixedRandom([try hex(m["scryptSalt"])]))
            try check(remade.serialized() == Data(file.utf8), "masterkeyFile bytes")
        }

        if let c = root["vaultConfig"] as? [String: Any], let token = c["token"] as? String, let id = c["vaultId"] as? String {
            try check(VaultConfig(vaultId: id).token(signedWith: key) == token, "vaultConfig token")
            try check(try VaultConfig.verify(try VaultConfig.decodeUnverified(token), with: key).vaultId == id, "vaultConfig verify")
        }

        for d in root["dirPaths"] as? [[String: Any]] ?? [] {
            try check(names.dirPath(d["dirId"] as? String ?? "?") == d["path"] as? String, "dirPath")
        }

        for n in root["names"] as? [[String: Any]] ?? [] {
            let name = n["name"] as? String ?? "", parent = n["parentDirId"] as? String ?? "", enc = n["encName"] as? String ?? ""
            try check(names.encrypt(name, parentDirId: parent) == enc, "name encrypt \(name)")
            try check((try? names.decrypt(enc, parentDirId: parent)) == name.precomposedStringWithCanonicalMapping, "name decrypt")
            if let s = n["shortened"] as? String { try check(NameCipher.shortened(enc) == s, "shortened") }
        }

        for f in root["fileContent"] as? [[String: Any]] ?? [] {
            let size = f["plaintextSize"] as? Int ?? -1
            let h = FileCipher.Header(nonce: try hex(f["headerNonce"]), contentKey: try hex(f["contentKey"]))
            let nonces = try (f["chunkNonces"] as? [String] ?? []).map { try hex($0) }
            let plain = pattern(size)
            var c = try FileCipher.encryptHeader(h, encKey: key.encKey)
            for (i, nonce) in nonces.enumerated() {
                let part = plain[(i * FileCipher.chunkPlainSize)..<min(size, (i + 1) * FileCipher.chunkPlainSize)]
                c += try FileCipher.encryptChunk(part, index: UInt64(i), header: h, nonce: nonce)
            }
            try check(Encoding.hex(SHA256.hash(data: c)) == f["ciphertextSha256"] as? String, "fileContent \(size)")
            if let full = f["ciphertext"] { try check(c == (try hex(full)), "fileContent bytes \(size)") }
            try check(try FileCipher.decrypt(c, encKey: key.encKey) == plain, "fileContent decrypt \(size)")
            try check(FileCipher.cleartextSize(ciphertextSize: c.count) == size, "cleartextSize \(size)")
        }

        if let r = root["recovery"] as? [String: Any], let file = r["file"] as? String,
           let phraseText = r["phrase"] as? String, let id = r["vaultId"] as? String {
            let phrase = try RecoveryPhrase(phrase: phraseText)
            try check(phrase.entropy == (try hex(r["entropy"])), "recovery phrase")
            try check(try RecoveryFile(data: Data(file.utf8)).unlock(phrase, vaultId: id) == key, "recovery unlock")
            let remade = try RecoveryFile.make(key, phrase: phrase, vaultId: id, random: FixedRandom([try hex(r["salt"]), try hex(r["nonce"])]))
            try check(remade.serialized() == Data(file.utf8), "recovery bytes")
        }
    }
}

/// 按顺序吐出预先给定的字节（测试向量里"指定盐 / nonce"用）。
final class FixedRandom: RandomSource {
    private var queue: [Data]
    init(_ queue: [Data]) { self.queue = queue }
    func bytes(_ count: Int) -> Data {
        let d = queue.removeFirst()
        precondition(d.count == count, "FixedRandom: expected \(count) bytes, queued \(d.count)")
        return d
    }
}
